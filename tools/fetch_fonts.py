"""Download the latin subsets of the Google Fonts used by NOVA and write fonts/fonts.css.

Self-hosting keeps the app working offline once loaded (festival wifi).
Run from the repository root: python3 tools/fetch_fonts.py
"""
import re, urllib.request, pathlib

URL = ("https://fonts.googleapis.com/css2?family=Pixelify+Sans:wght@400;700&family=Silkscreen:wght@400;700"
       "&family=Jersey+10&family=Press+Start+2P&family=IBM+Plex+Sans:ital,wght@0,400;0,500;0,600;1,400"
       "&family=IBM+Plex+Mono:wght@400;500;600&display=swap")
UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36"
out = pathlib.Path("fonts")
out.mkdir(exist_ok=True)

css = urllib.request.urlopen(urllib.request.Request(URL, headers={"User-Agent": UA})).read().decode()
blocks = re.findall(r"/\* (\S+) \*/\s*(@font-face \{.*?\})", css, re.S)
result = []
for subset, block in blocks:
    if subset != "latin":
        continue
    family = re.search(r"font-family: '([^']+)'", block).group(1)
    style = re.search(r"font-style: (\w+)", block).group(1)
    weight = re.search(r"font-weight: (\d+)", block).group(1)
    url = re.search(r"url\((\S+?)\)", block).group(1)
    name = f"{family.replace(' ', '')}-{weight}{'i' if style == 'italic' else ''}.woff2"
    (out / name).write_bytes(urllib.request.urlopen(url).read())
    result.append(block.replace(url, name))
    print("saved", name)
(out / "fonts.css").write_text("/* Generated by tools/fetch_fonts.py (latin subsets, self-hosted). */\n" + "\n".join(result) + "\n")
